#!/usr/bin/env python3
"""optcov -- how often does each ClaudeEPQ optimisation fire on generated programs?

  tools/optcov.py [--profile P ...] [--seed S] [--count N] [--jobs J] [--epq build/epq]
                  [--dir DIR_OF_EPQ_FILES] [--json OUT] [--show FEATURE]

For every program (generated by tools/epqgen.py, or every *.epq in --dir) it runs
the front end only (no C compiler, no new binaries):

  epq --dump-types FILE                       records: fixed / nullable regions
  epq --dump-tir-after=P FILE                 for P in region-info, simplify, litcmp,
                                              inline, recur, pairs, ifconv, appendopt,
                                              listopt, simplify2, reclaim
  epq --no-pass=constants --dump-tir-after=region-info FILE

A pass "fires" when its dump differs from the dump after the previous pass; a few
features are refined by counting ops in that pass's output (Reserve / AppendRange,
Select, Free, Pair*, While added by recur = tail-call loop, InlineBlock added by
recur = self-unrolling).  `demoted` = some global demoted to a local of main;
`constants` = the constants step changed the TIR.  Programs that do not compile
(injected compile errors) are left out of the denominator.

Prints a table profile x feature: % of programs in which the feature fires at
least once.  --show F prints the seeds of programs where F fires / does not fire.
"""
import argparse
import concurrent.futures as cf
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import epqlib  # noqa: E402
import epqgen  # noqa: E402

CHAIN = ["region-info", "simplify", "litcmp", "inline", "recur", "pairs", "ifconv",
         "appendopt", "listopt", "simplify2", "reclaim"]
FEATURES = ["rec_fixed", "rec_null", "pairs", "inline", "recur", "recur_loop", "recur_unroll",
            "recur_cse", "ifconv", "app_reserve", "app_range", "listopt", "litcmp", "reclaim",
            "simplify", "demoted", "constants"]


def run(cmd, timeout=30):
    try:
        p = subprocess.run(cmd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                           stderr=subprocess.DEVNULL, timeout=timeout)
        return p.returncode, p.stdout.decode("utf-8", "replace")
    except subprocess.TimeoutExpired:
        return -1, ""


def ops(dump):
    c = {}
    prev = None
    for line in dump.split("\n"):
        m = re.match(r"\s+([A-Z][A-Za-z0-9]*)\b", line)
        if m:
            op = m.group(1)
            c[op] = c.get(op, 0) + 1
            if op == "InlineBlock" and prev == "Comma":
                c["CommaInline"] = c.get("CommaInline", 0) + 1
            prev = op
    return c


def measure(epq, path):
    rc, types = run([epq, "--dump-types", path])
    if rc != 0:
        return None
    f = {}
    regs = [l for l in types.split("\n") if re.match(r"\s+r\d+ ", l)]
    f["rec_fixed"] = any(re.search(r" record Rec#", l) for l in regs)
    f["rec_null"] = any(re.search(r" record Rec\?#", l) for l in regs)
    dumps = {}
    for p in CHAIN:
        rc, d = run([epq, "--dump-tir-after=" + p, path])
        if rc != 0:
            return None
        dumps[p] = d
    ch = {}
    for i in range(1, len(CHAIN)):
        ch[CHAIN[i]] = dumps[CHAIN[i]] != dumps[CHAIN[i - 1]]
    o = {p: ops(dumps[p]) for p in CHAIN}
    f["simplify"] = ch["simplify"] or ch["simplify2"]
    f["litcmp"] = ch["litcmp"]
    f["inline"] = ch["inline"]
    f["recur"] = ch["recur"]
    f["recur_loop"] = o["recur"].get("While", 0) > o["inline"].get("While", 0)
    f["recur_unroll"] = o["recur"].get("CommaInline", 0) > o["inline"].get("CommaInline", 0)
    f["recur_cse"] = ch["recur"] and not f["recur_loop"] and not f["recur_unroll"]
    f["pairs"] = ch["pairs"] and any(k.startswith("Pair") for k in o["pairs"])
    f["ifconv"] = o["ifconv"].get("Select", 0) > o["pairs"].get("Select", 0)
    f["app_reserve"] = o["appendopt"].get("Reserve", 0) > 0
    f["app_range"] = o["appendopt"].get("AppendRange", 0) > 0
    f["listopt"] = ch["listopt"]
    f["reclaim"] = o["reclaim"].get("Free", 0) > o["simplify2"].get("Free", 0)
    g = dumps["region-info"].split("regions:")[0]
    f["demoted"] = " demoted" in g
    rc, d = run([epq, "--no-pass=constants", "--dump-tir-after=region-info", path])
    f["constants"] = rc == 0 and d != dumps["region-info"]
    return f


def job(args):
    epq, d, seed, profile, path = args
    if path is None:
        src, inp, info = epqgen.generate(seed, profile)
        profile = info["profile"]
        path = os.path.join(d, "c_%s_%d.epq" % (profile, seed))
        with open(path, "w") as fh:
            fh.write(src)
    r = measure(epq, path)
    return seed, profile, path, r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", action="append", default=None)
    ap.add_argument("--seed", type=int, default=700000)
    ap.add_argument("--count", type=int, default=1000)
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--epq", default=epqlib.NEW_BIN)
    ap.add_argument("--dir", default=None)
    ap.add_argument("--json", default=None)
    ap.add_argument("--show", default=None)
    a = ap.parse_args()
    d = os.path.join(epqlib.BUILD, "optcov")
    os.makedirs(d, exist_ok=True)
    jobs = []
    if a.dir:
        for root, _, fs in os.walk(a.dir):
            for fn in sorted(fs):
                if fn.endswith(".epq"):
                    jobs.append((a.epq, d, 0, os.path.basename(a.dir.rstrip("/")), os.path.join(root, fn)))
    else:
        for p in a.profile or ["clean", "mixed", "nasty"]:
            for i in range(a.count):
                jobs.append((a.epq, d, a.seed + i, p, None))
    res = {}
    seeds = {}
    with cf.ThreadPoolExecutor(a.jobs) if a.dir else cf.ProcessPoolExecutor(a.jobs) as ex:
        for seed, prof, path, r in ex.map(job, jobs, chunksize=1 if a.dir else 4):
            st = res.setdefault(prof, {"n": 0, "nc": 0, **{k: 0 for k in FEATURES}})
            st["n"] += 1
            if r is None:
                continue
            st["nc"] += 1
            for k in FEATURES:
                if r[k]:
                    st[k] += 1
                seeds.setdefault((prof, k, bool(r[k])), []).append(path if a.dir else seed)
    hdr = "%-10s %5s " % ("profile", "n") + " ".join("%6s" % k[:6] for k in FEATURES)
    print("feature columns: " + ", ".join(FEATURES))
    print(hdr)
    for prof, st in res.items():
        nc = max(st["nc"], 1)
        print("%-10s %5d " % (prof, st["nc"]) + " ".join("%6.1f" % (100.0 * st[k] / nc) for k in FEATURES))
    if a.json:
        with open(a.json, "w") as fh:
            json.dump(res, fh, indent=1)
    if a.show:
        for prof in res:
            for v in (True, False):
                print("%s %s=%s: %s" % (prof, a.show, v, seeds.get((prof, a.show, v), [])[:15]))


if __name__ == "__main__":
    main()
